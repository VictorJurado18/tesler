def svg(name: str, color: str = "#ffffff", stroke: float = 1.75) -> bytes:
    body = PATHS.get(name, PATHS["file"])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>').encode()


@lru_cache(maxsize=512)
def _image(name: str, px: int, rgba: tuple, stroke: float) -> QImage:
    from PySide6.QtSvg import QSvgRenderer
    color = QColor(*rgba)
    r = QSvgRenderer(QByteArray(svg(name, color.name(), stroke)))
    img = QImage(px, px, QImage.Format_ARGB32_Premultiplied)
    img.fill(Qt.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.Antialiasing)
    p.setOpacity(color.alphaF())
    r.render(p, QRectF(0, 0, px, px))
    p.end()
    return img


def icon_image(name: str, size: float, color: QColor, dpr: float = 2.0, stroke: float = 1.75) -> QImage:
    px = max(8, round(size * dpr))
    img = QImage(_image(name, px, (color.red(), color.green(), color.blue(), color.alpha()), stroke))
    img.setDevicePixelRatio(dpr)
    return img


def icon_pixmap(name: str, size: float, color: QColor, dpr: float = 2.0) -> QPixmap:
    return QPixmap.fromImage(icon_image(name, size, color, dpr))


def qicon(name: str, color: QColor, size: int = 16) -> QIcon:
    ic = QIcon()
    for dpr in (1.0, 1.5, 2.0, 3.0):
        ic.addPixmap(icon_pixmap(name, size, color, dpr))
    return ic


def draw(p: QPainter, name: str, rect: QRectF, color: QColor, stroke: float = 1.75) -> None:
    """Paint an icon into `rect` (logical px) at the painter's device scale."""
    dpr = max(1.0, p.device().devicePixelRatioF() if p.device() else 1.0) * max(1.0, p.transform().m11())
    img = icon_image(name, rect.width(), color, dpr, stroke)
    p.drawImage(rect, img)


def write_svg_file(name: str, color: str) -> str:
    """For stylesheet `image: url(...)` (checkbox tick, combo arrow): a cached temp file."""
    import hashlib
    import os
    import tempfile
    data = svg(name, color, 2.2)
    d = os.path.join(tempfile.gettempdir(), "dragshift-icons")
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, f"{name}-{hashlib.md5(data).hexdigest()[:8]}.svg")
    if not os.path.exists(path):
        with open(path, "wb") as f:
            f.write(data)
    return path.replace("\\", "/")
